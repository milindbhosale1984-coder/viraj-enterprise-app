export const ALL_METRO_STATIONS = [
  ...PUNE_PURPLE_LINE_STATIONS,
  ...PUNE_AQUA_LINE_STATIONS.filter((s) => s.stationCode !== 'CIVC'), // avoid duplicate interchange entry
];

// Helper to calculate Pune Metro Fare between two stations
export function calculatePuneMetroFare(
  sourceStationId: string,
  destStationId: string
): {
  fare: number;
  stationsCount: number;
  durationMins: number;
  requiresInterchange: boolean;
} {
  if (sourceStationId === destStationId) {
    return { fare: 10, stationsCount: 0, durationMins: 0, requiresInterchange: false };
  }

  const s1 = [...PUNE_PURPLE_LINE_STATIONS, ...PUNE_AQUA_LINE_STATIONS].find(
    (s) => s.id === sourceStationId
  );
  const s2 = [...PUNE_PURPLE_LINE_STATIONS, ...PUNE_AQUA_LINE_STATIONS].find(
    (s) => s.id === destStationId
  );

  if (!s1 || !s2) {
    return { fare: 15, stationsCount: 4, durationMins: 10, requiresInterchange: false };
  }

  const isSameLine =
    s1.line === s2.line ||
    s1.line === 'interchange' ||
    s2.line === 'interchange';

  let stationsCount = 0;
  let requiresInterchange = false;

  if (isSameLine) {
    stationsCount = Math.abs(s1.stationNumber - s2.stationNumber);
  } else {
    requiresInterchange = true;
    const s1ToCivil = Math.abs(s1.stationNumber - (s1.line === 'purple' ? 11 : 9));
    const civilToS2 = Math.abs(s2.stationNumber - (s2.line === 'purple' ? 11 : 9));
    stationsCount = s1ToCivil + civilToS2;
  }

  // Official Pune Metro Fare slabs:
  // 1 - 3 stations: ₹10
  // 4 - 6 stations: ₹15
  // 7 - 9 stations: ₹20
  // 10 - 13 stations: ₹25
  // 14 - 17 stations: ₹30
  // 18+ stations: ₹35
  let fare = 10;
  if (stationsCount >= 18) fare = 35;
  else if (stationsCount >= 14) fare = 30;
  else if (stationsCount >= 10) fare = 25;
  else if (stationsCount >= 7) fare = 20;
  else if (stationsCount >= 4) fare = 15;
  else fare = 10;

  const durationMins = Math.max(5, stationsCount * 2 + (requiresInterchange ? 5 : 0));

  return {
    fare,
    stationsCount,
    durationMins,
    requiresInterchange,
  };
}
